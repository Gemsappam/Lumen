def live_state() -> str:
    parts = []
    try:
        from .bot import blockers_text
        parts.append(blockers_text()[0][:1500])
    except Exception:
        pass
    try:
        from .lastmile import pending
        miss = pending()["missing"]
        if miss:
            parts.append("Нет доставки до Бауманской: " + ", ".join(x["awb"] for x in miss[:10]))
    except Exception:
        pass
    try:
        from .packing import targets
        parts.append(f"Подключено чатов пакингов: {len(targets())}")
    except Exception:
        pass
    try:
        from .main import VERSION
        parts.append("Версия бота: " + VERSION)
    except Exception:
        pass
    return "\n".join(parts)


async def answer(question: str) -> str:
    from . import ai
    from .config import PARSE_MODEL
    if not ai.client:
        return "AI не подключён (нет ключа) — смотри список команд: /help"
    msg = await ai._call(dict(
        model=ai.model_id(PARSE_MODEL), max_tokens=1200,
        system=("Ты — справка по Telegram-боту LumenFinance. Отвечай по-русски, коротко и по делу, по шагам: что нажать / "
                "какую команду написать. Опирайся только на руководство и текущее состояние ниже; если ответа там нет — "
                "честно скажи и предложи переслать вопрос с бэкапом разработчику. Ничего не выдумывай.\n\nРУКОВОДСТВО:\n"
                + GUIDE + "\n\nТЕКУЩЕЕ СОСТОЯНИЕ:\n" + live_state()),
        messages=[{"role": "user", "content": question}]))
    return "".join(getattr(b, "text", "") for b in msg.content).strip() or "Не смог ответить — попробуй переформулировать."
